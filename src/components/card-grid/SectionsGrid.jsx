const formatSourceFromUrl = (urlStr) => {
  if (!urlStr || typeof urlStr !== 'string') return '';
  try {
    let hostname = urlStr.trim();
    if (hostname.includes('://')) {
      hostname = new URL(hostname).hostname;
    } else {
      hostname = hostname.split('/')[0];
    }
    hostname = hostname.replace(/^www\./i, '').toLowerCase();

    if (KNOWN_SOURCES[hostname]) {
      return KNOWN_SOURCES[hostname];
    }

    const parts = hostname.split('.');
    if (parts.length >= 2) {
      const brand = parts[0];
      return brand.charAt(0).toUpperCase() + brand.slice(1);
    }
    return hostname.charAt(0).toUpperCase() + hostname.slice(1);
  } catch (e) {
    return '';
  }
};

export const getCleanSectionMeta = ({ section_title, section_type, page_url, parentWebsite }) => {
  const rawTitle = typeof section_title === 'string' ? section_title.trim() : '';
  const rawType = typeof section_type === 'string' ? section_type.trim() : '';

  // Check if string is a raw hash, UUID, or autogenerated file ID
  const isHashOrId = (str) => {
    if (!str) return true;
    const cleanStr = str.replace(/\.[a-zA-Z0-9]+$/, '');
    if (/^[0-9a-fA-F]{16,}$/.test(cleanStr)) return true;
    if (/^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/i.test(cleanStr)) return true;
    if (/^\d{10,}_[0-9a-zA-Z]+$/.test(cleanStr)) return true;
    return false;
  };

  // 1. Determine Section Name
  let sectionName = '';
  if (rawTitle && !isHashOrId(rawTitle)) {
    sectionName = rawTitle.replace(/\.(png|jpe?g|webp|gif|svg|mp4|webm|mov)$/i, '');
  } else if (rawType && rawType !== 'Custom' && rawType !== 'Other') {
    sectionName = rawType;
  } else if (rawTitle) {
    sectionName = rawTitle;
  } else {
    sectionName = 'Section';
  }

  // 2. Determine Company / Source Name
  let sourceName = '';
  if (parentWebsite?.title && typeof parentWebsite.title === 'string' && parentWebsite.title.trim()) {
    sourceName = parentWebsite.title.trim();
  } else if (parentWebsite?.normalised_url) {
    sourceName = formatSourceFromUrl(parentWebsite.normalised_url);
  } else if (page_url) {
    sourceName = formatSourceFromUrl(page_url);
  }

  if (sourceName && sourceName.toLowerCase() === sectionName.toLowerCase()) {
    sourceName = '';
  }

  return { sectionName, sourceName };
};

export const SectionCard = ({ 
  id, 
  section_type, 
  section_title, 
  image_url, 
  thumbnail_url,
  page_url, 
  status,
  parentWebsite,
  onToast,
  onEditSection,
  onUpdateSection,
  onDeleteSection
}) => {
  const [showMenu, setShowMenu] = useState(false);
  const [showRenameModal, setShowRenameModal] = useState(false);
  const [showDeleteModal, setShowDeleteModal] = useState(false);
  const [renameInput, setRenameInput] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [isSaved, setIsSaved] = useState(() => {
    try {
      const saved = JSON.parse(localStorage.getItem('saved_sections') || '{}');
      return !!saved[id || image_url];
    } catch (e) {
      return false;
    }
  });
  const [toasts, setToasts] = useState([]);
  const menuRef = useRef(null);

  const isVideo = isVideoMedia(image_url);
  const videoRef = useRef(null);

  useEffect(() => {
    if (isVideo && videoRef.current) {
      videoRef.current.defaultMuted = true;
      videoRef.current.muted = true;
      videoRef.current.play().catch(() => {});
    }
  }, [image_url, isVideo]);

  const addToast = (message, type = 'success') => {
    const toastId = Date.now() + Math.random();
    setToasts(prev => [...prev, { id: toastId, message, type }]);
    setTimeout(() => {
      setToasts(prev => prev.filter(t => t.id !== toastId));
    }, 3500);
  };

  // Clean single-line section metadata: "Section Name | Company / Source Name"
  const { sectionName, sourceName } = getCleanSectionMeta({
    section_title,
    section_type,
    page_url,
    parentWebsite
  });

  useEffect(() => {
    const handleClickOutside = (e) => {
      if (menuRef.current && !menuRef.current.contains(e.target)) {
        setShowMenu(false);
      }
    };
    if (showMenu) {
      document.addEventListener('mousedown', handleClickOutside);
    }
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, [showMenu]);

  // Lock body scroll and disable background card hovers while any modal is open
  useEffect(() => {
    if (showRenameModal || showDeleteModal) {
      const originalOverflow = document.body.style.overflow;
      document.body.style.overflow = 'hidden';
      document.body.classList.add('has-modal-open');

      const handleGlobalKeyDown = (e) => {
        if (e.key === 'Escape') {
          setShowRenameModal(false);
          setShowDeleteModal(false);
        }
      };
      window.addEventListener('keydown', handleGlobalKeyDown);

      return () => {
        document.body.style.overflow = originalOverflow;
        document.body.classList.remove('has-modal-open');
        window.removeEventListener('keydown', handleGlobalKeyDown);
      };
    }
  }, [showRenameModal, showDeleteModal]);

  const handleToggleSave = (e) => {
    e.stopPropagation();
    const nextState = !isSaved;
    setIsSaved(nextState);
    const triggerToast = onToast || addToast;
    try {
      const saved = JSON.parse(localStorage.getItem('saved_sections') || '{}');
      if (nextState) {
        saved[id || image_url] = true;
        triggerToast('Saved');
      } else {
        delete saved[id || image_url];
        triggerToast('Removed from saved', 'info');
      }
      localStorage.setItem('saved_sections', JSON.stringify(saved));
    } catch (err) {
      triggerToast(nextState ? 'Saved' : 'Removed from saved');
    }
  };

  const handleCopyImage = async (e) => {
    e.stopPropagation();
    const triggerToast = onToast || addToast;
    try {
      const response = await fetch(image_url, { mode: 'cors' });
      if (!response.ok) throw new Error('Fetch failed');
      const blob = await response.blob();

      const img = new Image();
      img.crossOrigin = 'anonymous';
      const objectUrl = URL.createObjectURL(blob);

      await new Promise((resolve, reject) => {
        img.onload = resolve;
        img.onerror = reject;
        img.src = objectUrl;
      });

      const canvas = document.createElement('canvas');
      canvas.width = img.naturalWidth || img.width || 800;
      canvas.height = img.naturalHeight || img.height || 600;
      const ctx = canvas.getContext('2d');
      ctx.drawImage(img, 0, 0);
      URL.revokeObjectURL(objectUrl);

      canvas.toBlob(async (pngBlob) => {
        if (pngBlob && navigator.clipboard && window.ClipboardItem) {
          try {
            await navigator.clipboard.write([
              new ClipboardItem({ 'image/png': pngBlob })
            ]);
            triggerToast('Image copied');
          } catch (clipErr) {
            await navigator.clipboard.writeText(image_url);
            triggerToast('Image copied');
          }
        } else {
          await navigator.clipboard.writeText(image_url);
          triggerToast('Image copied');
        }
      }, 'image/png');
    } catch (err) {
      try {
        await navigator.clipboard.writeText(image_url);
        triggerToast('Image copied');
      } catch (err2) {
        triggerToast('Failed to copy image', 'error');
      }
    }
  };

  const handleDownloadImage = async (e) => {
    e.stopPropagation();
    const triggerToast = onToast || addToast;
    triggerToast('Download started');
    try {
      const resp = await fetch(image_url);
      const blob = await resp.blob();
      const blobUrl = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = blobUrl;
      const ext = image_url.split('.').pop().split('?')[0] || 'png';
      const safeName = (sectionName || 'section-image').toLowerCase().replace(/[^a-z0-9]+/g, '-');
      a.download = `${safeName}.${ext}`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      setTimeout(() => URL.revokeObjectURL(blobUrl), 1000);
    } catch (err) {
      const a = document.createElement('a');
      a.href = image_url;
      a.download = 'section-image.png';
      a.target = '_blank';
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
    }
  };

  const handleOpenEdit = (e) => {
    e.stopPropagation();
    setShowMenu(false);
    if (onEditSection) {
      onEditSection({
        id,
        section_type,
        section_title,
        image_url,
        thumbnail_url,
        page_url,
        status,
        submissions: parentWebsite
      });
    }
  };

  const handleOpenRename = (e) => {
    e.stopPropagation();
    setShowMenu(false);
    setRenameInput(sectionName);
    setShowRenameModal(true);
  };

  const handleOpenDelete = (e) => {
    e.stopPropagation();
    setShowMenu(false);
    setShowDeleteModal(true);
  };

  const handleSaveRename = async (e) => {
    e?.preventDefault();
    if (!renameInput.trim()) return;
    setIsSubmitting(true);

    const updatedTitle = sanitizeSectionName(renameInput) || renameInput.trim();
    const triggerToast = onToast || addToast;
    
    // Immediate UI update
    if (onUpdateSection) {
      onUpdateSection(id, { section_title: updatedTitle, section_type: updatedTitle });
    }

    // Persist to DB
    await updateSectionTitleInDB({ id, image_url }, updatedTitle);

    setIsSubmitting(false);
    setShowRenameModal(false);
    triggerToast('Section renamed');
  };

  const handleConfirmDelete = async (e) => {
    e?.preventDefault();
    setIsSubmitting(true);
    const triggerToast = onToast || addToast;

    // Immediate UI update
    if (onDeleteSection) {
      onDeleteSection(id);
    }

    // Persist to DB
    await deleteSectionFromDB({ id, image_url, thumbnail_url });

    setIsSubmitting(false);
    setShowDeleteModal(false);
    triggerToast('Section deleted');
  };

  return (
    <div className="card-container section-card-container" style={{ textDecoration: 'none', position: 'relative' }}>
      <div className="card-image-wrapper section-card-image-wrapper">
        {isVideo ? (
          <video 
            ref={videoRef}
            src={image_url} 
            className="card-image section-card-image" 
            autoPlay
            muted 
            playsInline 
            loop
            preload="auto"
          />
        ) : (
          <img src={image_url} alt={sectionName} className="card-image section-card-image" loading="lazy" />
        )}
        
        {/* Card Overlay & Bottom Center Action Tabs Bar */}
        <div className="card-overlay">
          <div className="card-action-bar card-action-tabs" onClick={(e) => e.stopPropagation()}>
            <button 
              type="button" 
              className={`card-action-tab-btn action-save ${isSaved ? 'is-saved' : ''}`}
              onClick={handleToggleSave}
              aria-label="Save"
            >
              {isSaved ? <BookmarkSimple size={16} weight="fill" /> : <BookmarkSimple size={16} />}
            </button>

            <button 
              type="button" 
              className="card-action-tab-btn action-copy"
              onClick={handleCopyImage}
              aria-label="Copy image"
            >
              <CopySimple size={16} />
            </button>

            <button 
              type="button" 
              className="card-action-tab-btn action-download"
              onClick={handleDownloadImage}
              aria-label="Download image"
            >
              <DownloadSimple size={16} />
            </button>

            <button 
              type="button" 
              className="card-action-tab-btn action-open"
              onClick={(e) => { e.stopPropagation(); window.open(page_url || image_url, '_blank'); }}
              aria-label="Open"
            >
              <ArrowUpRight size={16} />
            </button>
          </div>
        </div>

        {/* Compact ••• Action Menu Button */}
        <div className="card-menu-container" ref={menuRef} onClick={(e) => e.stopPropagation()}>
          <button 
            type="button" 
            className={`card-menu-btn ${showMenu ? 'active' : ''}`} 
            onClick={() => setShowMenu(prev => !prev)}
            title="Options"
          >
            <MoreVertical size={16} />
          </button>

          {showMenu && (
            <div className="card-dropdown-menu">
              <button type="button" className="card-dropdown-item" onClick={handleOpenEdit}>
                <Edit size={14} className="card-dropdown-icon" />
                <span>Edit</span>
              </button>
              <button type="button" className="card-dropdown-item" onClick={handleOpenRename}>
                <Pencil size={14} className="card-dropdown-icon" />
                <span>Rename</span>
              </button>
              <button type="button" className="card-dropdown-item delete-item" onClick={handleOpenDelete}>
                <Trash2 size={14} className="card-dropdown-icon" />
                <span>Delete</span>
              </button>
            </div>
          )}
        </div>
      </div>

      <div className="section-card-meta">
        <div className="section-card-title-row">
          <span className="section-card-name" title={sectionName}>{sectionName}</span>
          {sourceName && (
            <>
              <span className="section-card-divider">|</span>
              <span className="section-card-source" title={sourceName}>{sourceName}</span>
            </>
          )}
        </div>
        {status === 'Draft' && (
          <span className="section-draft-badge">Draft</span>
        )}
      </div>

      {/* Layout 2: Compact Centered Micro-Dialog (Portaled to document.body) */}
      {showRenameModal && typeof document !== 'undefined' && createPortal(
        <div 
          className="rename-micro-overlay" 
          onClick={() => setShowRenameModal(false)}
          onKeyDown={(e) => { if (e.key === 'Escape') setShowRenameModal(false); }}
        >
          <div className="rename-micro-dialog" onClick={(e) => e.stopPropagation()}>
            <div className="rename-micro-header">
              <span className="rename-micro-title">Rename Section</span>
              <button 
                type="button" 
                className="rename-micro-close" 
                onClick={() => setShowRenameModal(false)}
                aria-label="Close"
              >
                <X size={14} />
              </button>
            </div>
            <form onSubmit={handleSaveRename}>
              <div className="rename-micro-body">
                <input 
                  type="text" 
                  className="rename-micro-input"
                  value={renameInput}
                  onChange={(e) => setRenameInput(e.target.value)}
                  onKeyDown={(e) => {
                    if (e.key === 'Escape') {
                      e.stopPropagation();
                      setShowRenameModal(false);
                    }
                  }}
                  placeholder="Enter section name..."
                  autoFocus
                  required
                />
              </div>
              <div className="rename-micro-footer">
                <button 
                  type="button" 
                  className="rename-micro-btn rename-micro-cancel" 
                  onClick={() => setShowRenameModal(false)} 
                  disabled={isSubmitting}
                >
                  Cancel <kbd className="rename-micro-kbd">Esc</kbd>
                </button>
                <button 
                  type="submit" 
                  className="rename-micro-btn rename-micro-save" 
                  disabled={isSubmitting || !renameInput.trim()}
                >
                  {isSubmitting ? 'Saving…' : <>Save <kbd className="rename-micro-kbd">↵</kbd></>}
                </button>
              </div>
            </form>
          </div>
        </div>,
        document.body
      )}

      {/* Delete Confirmation Modal (Portaled to document.body) */}
      {showDeleteModal && typeof document !== 'undefined' && createPortal(
        <div className="section-modal-overlay" onClick={() => setShowDeleteModal(false)}>
          <div className="section-modal-card" onClick={(e) => e.stopPropagation()}>
            <div className="section-modal-header">
              <h3>Delete section?</h3>
              <button type="button" className="section-modal-close" onClick={() => setShowDeleteModal(false)}>
                <X size={18} />
              </button>
            </div>
            <div className="section-modal-body">
              <p>This will remove this uploaded asset and its section data.</p>
            </div>
            <div className="section-modal-footer">
              <button type="button" className="section-modal-btn section-modal-btn-cancel" onClick={() => setShowDeleteModal(false)} disabled={isSubmitting}>
                Cancel
              </button>
              <button type="button" className="section-modal-btn section-modal-btn-danger" onClick={handleConfirmDelete} disabled={isSubmitting}>
                {isSubmitting ? 'Deleting...' : 'Delete'}
              </button>
            </div>
          </div>
        </div>,
        document.body
      )}

      {/* Ref.Design Toast Feedback Container (Portaled to document.body for bottom-center viewport alignment) */}
      {toasts.length > 0 && typeof document !== 'undefined' && createPortal(
        <div className="lm-toast-container">
          {toasts.map(toast => (
            <div key={toast.id} className="lm-toast">
              <div className={`lm-toast-icon lm-toast-${toast.type || 'success'}`}>
                {toast.type === 'error' ? <X size={13} strokeWidth={2.5} /> : <Check size={13} strokeWidth={2.5} />}
              </div>
              <span className="lm-toast-msg">{toast.message}</span>
              <button 
                type="button" 
                className="lm-toast-close" 
                onClick={() => setToasts(prev => prev.filter(t => t.id !== toast.id))}
                aria-label="Close notification"
              >
                <X size={14} />
              </button>
            </div>
          ))}
        </div>,
        document.body
      )}
    </div>
  );
};

export default function SectionsGrid({ selectedCategory }) {
  const [sections, setSections] = useState([]);
  const [loading, setLoading] = useState(true);
  const [fetchError, setFetchError] = useState(null);
  const [currentPage, setCurrentPage] = useState(1);
  const [editingSection, setEditingSection] = useState(null);
  const [isUploadOpen, setIsUploadOpen] = useState(false);
  const [toasts, setToasts] = useState([]);
  const cardsPerPage = 24;

  const addToast = (message, type = 'success') => {
    const toastId = Date.now() + Math.random();
    setToasts(prev => [...prev, { id: toastId, message, type }]);
    setTimeout(() => {
      setToasts(prev => prev.filter(t => t.id !== toastId));
    }, 3500);
  };

  const fetchSections = async () => {
    setLoading(true);
    try {
      let query = supabase
        .from('website_sections')
        .select(`
          id,
          section_type,
          section_title,
          image_url,
          page_url,
          status,
          created_at,
          submissions:website_id (
            id,
            title,
            normalised_url,
            logo_url
          )
        `)
        .order('created_at', { ascending: false });

      if (selectedCategory) {
        query = query.ilike('section_type', `%${selectedCategory}%`);
      }

      const { data, error } = await query;

      if (error) {
        console.error("Error fetching sections:", error);
        setFetchError(error.message || JSON.stringify(error));
      } else {
        setSections(data || []);
      }
    } catch (err) {
      console.error("Failed to fetch sections:", err);
      setFetchError(err.message || String(err));
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchSections();
  }, [selectedCategory]);

  const handleUpdateSection = (id, updatedFields) => {
    setSections(prev => prev.map(sec => sec.id === id ? { ...sec, ...updatedFields } : sec));
  };

  const handleDeleteSection = (id) => {
    setSections(prev => prev.filter(sec => sec.id !== id));
  };

  const [columnCount, setColumnCount] = useState(() => {
    if (typeof window === 'undefined') return 3;
    if (window.innerWidth <= 640) return 1;
    if (window.innerWidth <= 1024) return 2;
    return 3;
  });

  useEffect(() => {
    const handleResize = () => {
      const width = window.innerWidth;
      const nextCount = width <= 640 ? 1 : width <= 1024 ? 2 : 3;
      setColumnCount(prev => prev !== nextCount ? nextCount : prev);
    };
    window.addEventListener('resize', handleResize);
    return () => window.removeEventListener('resize', handleResize);
  }, []);

  const totalPages = Math.ceil(sections.length / cardsPerPage);
  const indexOfLastCard = currentPage * cardsPerPage;
  const indexOfFirstCard = indexOfLastCard - cardsPerPage;
  const currentCards = sections.slice(indexOfFirstCard, indexOfLastCard);

  // Distribute cards round-robin across columns for natural left-to-right flow
  const columns = Array.from({ length: columnCount }, () => []);
  currentCards.forEach((sec, index) => {
    columns[index % columnCount].push(sec);
  });

  const handlePageChange = (page) => {
    setCurrentPage(page);
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  if (fetchError) {
    return (
      <section className="card-grid-section" style={{ minHeight: '50vh', display: 'flex', alignItems: 'center', justifyContent: 'center', color: 'red' }}>
        <p>Error fetching sections: {fetchError}</p>
      </section>
    );
  }

  if (loading) {
    return (
      <section className="card-grid-section" style={{ minHeight: '50vh', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
        <p>Loading captured sections...</p>
      </section>
    );
  }

  if (sections.length === 0) {
    return (
      <section className="card-grid-section" style={{ minHeight: '50vh', display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', opacity: 0.7 }}>
        <LayoutTemplate size={36} style={{ marginBottom: 12, opacity: 0.5 }} />
        <p style={{ fontWeight: 500 }}>No sections captured yet.</p>
        <p style={{ fontSize: '13px', marginTop: 4 }}>Use the Ref.Design Extension with "Capture Section" to clip Hero, Pricing, or Bento Grid sections!</p>
      </section>
    );
  }

  return (
    <section className="card-grid-section">
      <div className="sections-masonry-grid">
        {columns.map((colCards, colIdx) => (
          <div key={colIdx} className="sections-masonry-col">
            {colCards.map((sec) => (
              <SectionCard 
                key={sec.id} 
                id={sec.id}
                section_type={sec.section_type}
                section_title={sec.section_title}
                image_url={sec.image_url}
                page_url={sec.page_url}
                status={sec.status}
                parentWebsite={sec.submissions}
                onEditSection={(sectionToEdit) => {
                  setEditingSection(sectionToEdit);
                  setIsUploadOpen(true);
                }}
                onUpdateSection={handleUpdateSection}
                onDeleteSection={handleDeleteSection}
                onToast={addToast}
              />
            ))}
          </div>
        ))}
      </div>
      {totalPages > 1 && (
        <Pagination 
          currentPage={currentPage} 
          totalPages={totalPages} 
          onPageChange={handlePageChange} 
        />
      )}

      {/* Sidebar Uploader Drawer */}
      <SectionUploadDrawer 
        isOpen={isUploadOpen}
        initialSection={editingSection}
        onClose={() => {
          setIsUploadOpen(false);
          setEditingSection(null);
        }}
        onUploadSuccess={({ status, isEdit }) => {
          addToast(status === 'Draft' ? 'Section saved as draft!' : (isEdit ? 'Section updated successfully!' : 'Section published!'));
          fetchSections();
        }}
      />

      {/* Global Ref.Design Toaster Container (Bottom Center Fixed via Portal) */}
      {toasts.length > 0 && typeof document !== 'undefined' && createPortal(
        <div className="lm-toast-container">
          {toasts.map(toast => (
            <div key={toast.id} className="lm-toast">
              <div className={`lm-toast-icon lm-toast-${toast.type || 'success'}`}>
                {toast.type === 'error' ? <X size={13} strokeWidth={2.5} /> : <Check size={13} strokeWidth={2.5} />}
              </div>
              <span className="lm-toast-msg">{toast.message}</span>
              <button 
                type="button" 
                className="lm-toast-close" 
                onClick={() => setToasts(prev => prev.filter(t => t.id !== toast.id))}
                aria-label="Close notification"
              >
                <X size={14} />
              </button>
            </div>
          ))}
        </div>,
        document.body
      )}
    </section>
  );
}

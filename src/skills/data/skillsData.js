/**
 * Format a raw star count to a human-readable string.
 * e.g. 161400 → "161.4K" | 47000 → "47K" | 811 → "811"
 */
export function formatStars(count) {
  if (count >= 1000) {
    const k = count / 1000;
    return k % 1 === 0 ? `${k}K` : `${k.toFixed(1)}K`;
  }
  return String(count);
}
